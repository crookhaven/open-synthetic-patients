#!/usr/bin/env python3
"""Builds catalog.json and CATALOG.md from every patients/<slug>/patient.json card.

Usage:
  python tools/build_catalog.py           # rewrite catalog.json and CATALOG.md
  python tools/build_catalog.py --check   # fail if either file is out of date

The hand-written facts come from each patient card. Counts (resources by type,
file size, profiles) are computed from the patient's bundles, so they never drift.
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATIENTS = ROOT / "patients"
CATALOG_JSON = ROOT / "catalog.json"
CATALOG_MD = ROOT / "CATALOG.md"


def bundle_stats(path):
    bundle = json.loads(path.read_text(encoding="utf-8-sig"))
    resources = [e.get("resource", {}) for e in bundle.get("entry", [])]
    types = Counter(r.get("resourceType", "?") for r in resources)
    profiles = sorted({
        p.split("/")[-1].split("|")[0]
        for r in resources
        for p in r.get("meta", {}).get("profile", [])
    })
    return {
        "file": path.name,
        "bytes": path.stat().st_size,
        "resource_count": len(resources),
        "resource_types": dict(sorted(types.items(), key=lambda kv: (-kv[1], kv[0]))),
        "profiles": profiles,
    }


def load_patients():
    patients = []
    for card_path in sorted(PATIENTS.glob("*/patient.json")):
        card = json.loads(card_path.read_text(encoding="utf-8"))
        folder = card_path.parent
        variants = {}
        for name, file_name in card.get("variants", {}).items():
            variants[name] = bundle_stats(folder / file_name)
        patients.append({**card, "path": f"patients/{folder.name}", "variant_stats": variants})
    return patients


def render_markdown(patients):
    lines = [
        "# Catalog",
        "",
        "Generated by `tools/build_catalog.py` from each patient's `patient.json`. Do not edit by hand.",
        "",
        "| Patient | Sex, born | Records | Good for | License |",
        "|---|---|---|---|---|",
    ]
    for p in patients:
        clean = p["variant_stats"].get("clean") or next(iter(p["variant_stats"].values()), {})
        records = clean.get("resource_count", "?")
        variants = ", ".join(p["variant_stats"].keys())
        uses = ", ".join(p.get("use_cases", []))
        lines.append(
            f"| [{p['name']}]({p['path']}/) | {p.get('sex', '?')}, {p.get('birth_date', '?')} "
            f"| {records} ({variants}) | {uses} | {p.get('license', '?')} |"
        )
    lines.append("")
    for p in patients:
        lines += [f"## {p['name']}", "", p.get("summary", ""), ""]
        if p.get("conditions"):
            lines.append("**Conditions:** " + "; ".join(p["conditions"]))
            lines.append("")
        src = p.get("source", {})
        source_text = src.get("method", "?")
        if src.get("based_on"):
            source_text += f", based on {src['based_on']}"
        lines.append(f"**Source:** {source_text}")
        lines.append("")
        lines.append(f"**License:** {p.get('license', '?')}. {p.get('attribution', '')}")
        lines.append("")
        for name, stats in p["variant_stats"].items():
            top = ", ".join(f"{k} {v}" for k, v in list(stats["resource_types"].items())[:8])
            lines.append(f"- `{name}`: `{stats['file']}`, {stats['resource_count']} resources ({top})")
        lines.append("")
    return "\n".join(lines)


def main():
    patients = load_patients()
    catalog = {"schema": "open-synthetic-patients/catalog/v1", "patients": patients}
    new_json = json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"
    new_md = render_markdown(patients)
    if "--check" in sys.argv:
        stale = [
            p.name for p, new in ((CATALOG_JSON, new_json), (CATALOG_MD, new_md))
            if not p.exists() or p.read_text(encoding="utf-8") != new
        ]
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run: python tools/build_catalog.py")
            return 1
        print(f"Catalog is up to date ({len(patients)} patients).")
        return 0
    CATALOG_JSON.write_text(new_json, encoding="utf-8")
    CATALOG_MD.write_text(new_md, encoding="utf-8")
    print(f"Wrote catalog.json and CATALOG.md ({len(patients)} patients).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
